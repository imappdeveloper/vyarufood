    public function __construct(
        public readonly ?int $id = null,
        public readonly ?string $uuid = null,
        public readonly ?string $kitchenCode = null,
        public readonly ?string $name = null,
        public readonly ?string $description = null,
        public readonly ?string $kitchenType = 'main_kitchen',
        public readonly ?string $managerName = null,
        public readonly ?string $managerMobile = null,
        public readonly ?string $managerEmail = null,
        public readonly ?int $countryId = null,
        public readonly ?int $stateId = null,
        public readonly ?int $cityId = null,
        public readonly ?int $areaId = null,
        public readonly ?int $deliveryZoneId = null,
        public readonly ?string $addressLine1 = null,
        public readonly ?string $addressLine2 = null,
        public readonly ?string $landmark = null,
        public readonly ?float $latitude = null,
        public readonly ?float $longitude = null,
        public readonly ?string $openingTime = null,
