    public static function fromArray(array $data): self
    {
        return new self(
            id: isset($data['id']) ? (int) $data['id'] : null,
            uuid: $data['uuid'] ?? null,
            kitchenCode: $data['kitchen_code'] ?? null,
            name: $data['name'] ?? null,
            description: $data['description'] ?? null,
            kitchenType: $data['kitchen_type'] ?? 'main_kitchen',
